import { PORTAL_SCHEMA } from './db.mjs';
import { ORDER_SCHEMA } from './orders.mjs';

const ddl = (PORTAL_SCHEMA + '\n' + ORDER_SCHEMA)
  .replace(/\bid INTEGER PRIMARY KEY/g, 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
  .replace(/\bexpires INTEGER\b/g, 'expires BIGINT')
  .replace(/\bBLOB\b/g, 'BYTEA');

function statements(query) {
  return {
    dialect: 'postgres',
    prepare(sql) {
      let index = 0;
      const text = sql.replace(/\?/g, () => '$' + ++index);
      return {
        get: async (...values) => (await query(text, values)).rows[0],
        all: async (...values) => (await query(text, values)).rows,
        run: async (...values) => ({ changes: (await query(text, values)).rowCount }),
      };
    },
  };
}

export async function openPostgres(connectionString, schema = 'houstonem_demo') {
  if (!/^[a-z][a-z0-9_]{0,62}$/.test(schema)) throw new Error('Invalid PostgreSQL schema name.');
  const uri = new URL(connectionString);
  if (!['postgresql:','postgres:'].includes(uri.protocol)) throw new Error('DATABASE_URL must use PostgreSQL.');
  // Use verified TLS explicitly. Neon supports the channel-bound SCRAM flow.
  for (const key of ['sslmode','sslcert','sslkey','sslrootcert','channel_binding','uselibpqcompat','options']) uri.searchParams.delete(key);
  const { Pool } = await import('pg');
  const pool = new Pool({
    connectionString: uri.toString(), ssl: { rejectUnauthorized: true }, enableChannelBinding: true,
    max: 5, connectionTimeoutMillis: 12000, idleTimeoutMillis: 15000,
  });
  pool.on('error', error => console.error('PostgreSQL idle connection error:', error.code || error.name));

  // Transaction pooling may switch physical connections: schema selection must
  // be set inside each transaction, not as an assumed persistent session setting.
  const scoped = async (work, initialize = false) => {
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      await client.query("SET LOCAL statement_timeout = '20s'");
      if (initialize) {
        await client.query('SELECT pg_advisory_xact_lock(hashtext($1))', ['houstonem-schema:' + schema]);
        await client.query(`CREATE SCHEMA IF NOT EXISTS "${schema}"`);
      }
      await client.query(`SET LOCAL search_path TO "${schema}", pg_catalog`);
      const result = await work(client);
      await client.query('COMMIT');
      return result;
    } catch (error) {
      try { await client.query('ROLLBACK'); } catch {}
      throw error;
    } finally { client.release(); }
  };

  try {
    await scoped(async client => {
      await client.query(ddl);
      if (!(await client.query('SELECT to_regclass($1) AS relation', [schema + '.users'])).rows[0].relation) {
        await client.query(`CREATE VIEW users AS SELECT c.id,c.email,c.name,c.company,
          EXISTS(SELECT 1 FROM administrators a WHERE a.customer_id=c.id) AS is_admin FROM customers c`);
      }
    }, true);
  } catch (error) { await pool.end(); throw error; }

  return {
    ...statements((sql, values) => scoped(client => client.query(sql, values))),
    transaction: work => scoped(client => work(statements((sql,values) => client.query(sql,values)))),
    close: () => pool.end(),
  };
}
